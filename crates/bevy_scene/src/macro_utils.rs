use bevy_platform::sync::atomic::AtomicU64;
use bevy_platform::sync::atomic::Ordering;

pub use bevy_platform::sync::LazyLock;

/// This is used by the [`bsn!`](crate::bsn) macro to generate compile-time only references to symbols. Currently this is used
/// to add IDE support for nested type names, as it allows us to pass the input Ident from the input to the output code.
pub const fn touch_type<T>() {}

/// This is used by the [`bsn!`](crate::bsn) derive to work around [this Rust limitation](https://github.com/rust-lang/rust/issues/86935).
/// A fix is implemented and on track for stabilization. If it is ever implemented, we can remove this.
pub type PathResolveHelper<T> = T;

/// A counter for generating unique IDs.
///
/// Used by the [`bsn!`](crate::bsn) and [`bsn_list!`](crate::bsn_list) macros to generate IDs for
/// [`SceneEntityReference`]s:
///
/// - Invocation IDs, which uniquely identify the location of a macro call
/// - Call IDs, which differentiate the entity references generated by successive evaluations of the
///   same scene
///
/// [`SceneEntityReference`]: bevy_ecs::template::SceneEntityReference
pub struct IdCounter(AtomicU64);

impl IdCounter {
    /// Create a new counter starting at 0.
    #[expect(
        clippy::new_without_default,
        reason = "Needs to be an associated const fn for use in static"
    )]
    pub const fn new() -> Self {
        Self(AtomicU64::new(0))
    }

    /// Get the current count and then increment this counter by 1.
    pub fn next(&self) -> u64 {
        self.0.fetch_add(1, Ordering::Relaxed)
    }
}

/// A global counter used to assign each [`bsn!`](crate::bsn) and [`bsn_list!`](crate::bsn_list)
/// macro invocation site a unique invocation ID.
///
/// [`SceneEntityReference`]s already take the source location (file, line, column) of the macro
/// invocation that created them, but that location [may not be unique][bevy#25407]. Invocation
/// IDs are used to ensure the uniqueness of each scene scope.
///
/// [`SceneEntityReference`]: bevy_ecs::template::SceneEntityReference
/// [bevy#25407]: https://github.com/bevyengine/bevy/issues/25407
pub static INVOCATION_ID_COUNTER: IdCounter = IdCounter::new();

/// Create a [`LazyLock`] that initializes to a unique invocation ID from [`INVOCATION_ID_COUNTER`].
///
/// Used for the invocation ID in entity references (see [`SceneEntityReference`]).
///
/// This allows callers to store the ID in a `static` so that each evaluation of the scene gets the
/// same ID. Returns a `LazyLock` because an ID is generated by calling [`IdCounter::next()`] which
/// cannot be `const`.
///
/// [`SceneEntityReference`]: bevy_ecs::template::SceneEntityReference
pub const fn get_lazy_invocation_id() -> LazyLock<u64> {
    fn init() -> u64 {
        INVOCATION_ID_COUNTER.next()
    }
    LazyLock::new(init)
}
